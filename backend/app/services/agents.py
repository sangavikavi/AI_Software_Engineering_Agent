import json
import logging
from typing import Dict, Any, List, TypedDict, Literal
from langgraph.graph import StateGraph, END

from app.services.llm import call_llm

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

# 1. State Definition
class AgentState(TypedDict):
    instruction: str                 # User request instruction
    codebase_context: List[str]      # Semantic code chunks retrieved via search
    plan: List[str]                  # Steps generated by the Planner
    current_step_index: int          # Next step index to execute
    proposed_changes: Dict[str, str] # Filepath -> Proposed Code Content
    test_results: Dict[str, Any]     # Success status, logs, counts
    review_feedback: Dict[str, Any]  # Approved status, feedback text
    status: str                      # planning, coding, testing, reviewing, ready, failed
    iterations: int                  # Loop counter to prevent infinite iteration
    history_logs: List[str]          # Live log records of agent transitions

# 2. Agent Node Implementations
def planner_node(state: AgentState) -> Dict[str, Any]:
    logger.info("--- Entering PLANNER Node ---")
    system_prompt = (
        "You are an expert software architect planner agent. "
        "Analyze the user's requirements and the codebase context. "
        "Generate a step-by-step task list to implement the requirement. "
        "Output ONLY a JSON array of strings representing the steps."
    )
    user_prompt = f"Requirement: {state['instruction']}\nContext:\n" + "\n".join(state["codebase_context"])
    
    response = call_llm(system_prompt, user_prompt)
    try:
        plan = json.loads(response)
        if not isinstance(plan, list):
            plan = [response]
    except Exception:
        plan = [response]
        
    history = list(state.get("history_logs", []))
    history.append("Planner: Analyzed requirement and generated implementation plan.")
    
    return {
        "plan": plan,
        "current_step_index": 0,
        "status": "coding",
        "history_logs": history
    }

def coder_node(state: AgentState) -> Dict[str, Any]:
    logger.info("--- Entering CODER Node ---")
    system_prompt = (
        "You are an expert coder agent. "
        "Generate the required code changes for the current step in the plan. "
        "Output a JSON object mapping file paths to their new complete file content."
    )
    
    user_prompt = (
        f"Instruction: {state['instruction']}\n"
        f"Plan: {json.dumps(state['plan'])}\n"
        f"Active Step Index: {state['current_step_index']}\n"
        f"Review Feedback: {json.dumps(state.get('review_feedback', {}))}\n"
        f"Test failures: {json.dumps(state.get('test_results', {}))}"
    )
    
    response = call_llm(system_prompt, user_prompt)
    try:
        changes = json.loads(response)
        if not isinstance(changes, dict):
            changes = {"app/main.py": response}
    except Exception:
        changes = {"app/main.py": response}
        
    history = list(state.get("history_logs", []))
    history.append(f"Coder: Formulated code changes for step {state['current_step_index'] + 1}.")
    
    return {
        "proposed_changes": changes,
        "status": "testing",
        "history_logs": history
    }

def tester_node(state: AgentState) -> Dict[str, Any]:
    logger.info("--- Entering TESTER Node ---")
    system_prompt = (
        "You are an automated testing agent. "
        "Check the proposed code changes for syntax and logic errors. "
        "Output ONLY a JSON object with keys: 'success' (boolean), 'logs' (string), "
        "'test_run_count' (int), and 'failures' (int)."
    )
    user_prompt = f"Proposed Changes:\n{json.dumps(state['proposed_changes'])}"
    
    response = call_llm(system_prompt, user_prompt)
    try:
        test_res = json.loads(response)
    except Exception:
        test_res = {"success": True, "logs": response, "test_run_count": 1, "failures": 0}
        
    history = list(state.get("history_logs", []))
    status_str = "passed" if test_res.get("success") else "failed"
    history.append(f"Tester: Verification tests {status_str}.")
    
    return {
        "test_results": test_res,
        "status": "reviewing" if test_res.get("success") else "coding",
        "iterations": state.get("iterations", 0) + (0 if test_res.get("success") else 1),
        "history_logs": history
    }

def reviewer_node(state: AgentState) -> Dict[str, Any]:
    logger.info("--- Entering REVIEWER Node ---")
    system_prompt = (
        "You are a senior code reviewer agent. "
        "Critique the code changes. Check if it complies with requirements and doesn't break existing patterns. "
        "Output ONLY a JSON object with keys: 'approved' (boolean) and 'feedback' (string)."
    )
    user_prompt = f"Requirements: {state['instruction']}\nCode Changes:\n{json.dumps(state['proposed_changes'])}"
    
    response = call_llm(system_prompt, user_prompt)
    try:
        review_res = json.loads(response)
    except Exception:
        review_res = {"approved": True, "feedback": response}
        
    history = list(state.get("history_logs", []))
    status_str = "Approved" if review_res.get("approved") else "Requested Revisions"
    history.append(f"Reviewer: {status_str} - {review_res.get('feedback')}")
    
    return {
        "review_feedback": review_res,
        "status": "ready" if review_res.get("approved") else "coding",
        "iterations": state.get("iterations", 0) + (0 if review_res.get("approved") else 1),
        "history_logs": history
    }

# 3. Conditional Routers
def should_continue_after_test(state: AgentState) -> Literal["reviewer", "coder", "failed"]:
    res = state.get("test_results", {})
    if res.get("success"):
        return "reviewer"
        
    # Prevent infinite coder-tester loops
    if state.get("iterations", 0) >= 3:
        logger.warning("Tester loop threshold exceeded. Aborting agent execution.")
        return "failed"
    return "coder"

def should_continue_after_review(state: AgentState) -> Literal["end", "coder", "failed"]:
    res = state.get("review_feedback", {})
    if res.get("approved"):
        return "end"
        
    # Prevent infinite coder-reviewer loops
    if state.get("iterations", 0) >= 4:
        logger.warning("Reviewer loop threshold exceeded. Aborting agent execution.")
        return "failed"
    return "coder"

# 4. State Graph Assembly
workflow = StateGraph(AgentState)

# Add Nodes
workflow.add_node("planner", planner_node)
workflow.add_node("coder", coder_node)
workflow.add_node("tester", tester_node)
workflow.add_node("reviewer", reviewer_node)

# Add Edges
workflow.set_entry_point("planner")
workflow.add_edge("planner", "coder")
workflow.add_edge("coder", "tester")

workflow.add_conditional_edges(
    "tester",
    should_continue_after_test,
    {
        "reviewer": "reviewer",
        "coder": "coder",
        "failed": END
    }
)

workflow.add_conditional_edges(
    "reviewer",
    should_continue_after_review,
    {
        "end": END,
        "coder": "coder",
        "failed": END
    }
)

# Compile LangGraph
compiled_graph = workflow.compile()
